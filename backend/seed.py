"""
JIZO - Part 3 seed script (owner: Aayush, P3).

Fills a fresh database with the registry policies and a few representative
drill runs, so the dashboard has something to show and `/health` reports
real numbers without anyone running a drill first.

Run it with:

    .\\.venv\\Scripts\\python.exe -m backend.seed

## Why this works before P2 exists

The demo runs below are generated by **calling P1's scorer directly**.
`score_run(spec, events)` is a pure function - data in, data out - so we can
build a realistic `EvidenceEvent` timeline on the evidence bus, grade it,
and persist the result. No proxy, no network, no upstream API.

That matters for the build order: P2 (the protector) has not been written,
but P3 does not depend on it. This is how P3 stays unblocked.

## The numbers are cited, not invented

Doc Sec. 11.4 is the designated source ("Do not invent thresholds; use
defaults in Sec. 11.4"), and `backend/config.py` reads the same values from
`.env`. These are copied from published tuning in `notes/README.md` Sec. 1,
so a judge asking "why 25%?" gets a citation rather than a shrug.

`api_key` values are aligned to Part 2's merged `config.py`, which is the
running source of truth: Aditi's registry uses `weather` and `geocode`, and
`proxy.py` resolves policies through `load_policy(api_key)`. A registry row
keyed `open-meteo` would never be found, so the demo would fail on a missing
policy.

Note this means the build doc's own example log line (Sec. 7.3, which prints
`"api":"open-meteo"`) disagrees with the merged code. P2 landed first and its
180 tests depend on these names, so P3 follows P2. Worth raising so the log
example and the code end up saying the same thing.
"""

